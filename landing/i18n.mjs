export function detectLanguage(stored, browserLanguages) {
  if (stored === 'en' || stored === 'ru') return stored
  const first = (browserLanguages ?? []).find(Boolean) ?? ''
  return /^(ru|be|uk|kk)\b/i.test(first) ? 'ru' : 'en'
}
